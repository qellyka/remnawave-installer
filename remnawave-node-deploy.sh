if env_bool("RW_ENABLE_REALITY_GRPC"):
    tag = "reality-grpc"
    inbounds.append({
        "tag": tag,
        "listen": "0.0.0.0",
        "port": int(os.environ["RW_REALITY_GRPC_PORT"]),
        "protocol": "vless",
        "settings": {"clients": [], "decryption": "none"},
        "sniffing": {"enabled": True, "destOverride": ["http", "tls", "quic"]},
        "streamSettings": {
            "network": "grpc",
