                "serverNames": [os.environ["RW_REALITY_GRPC_SNI"]],
                "privateKey": os.environ["RW_REALITY_GRPC_PRIVATE_KEY"],
                "shortIds": [os.environ["RW_REALITY_GRPC_SHORTID"]]
            }
        }
    })

# ---- Reality + XHTTP (raw, direct connection — NOT CDN-compatible) ----
if env_bool("RW_ENABLE_REALITY_XHTTP"):
    tag = "reality-xhttp"
    inbounds.append({
        "tag": tag,
        "listen": "0.0.0.0",
        "port": int(os.environ["RW_REALITY_XHTTP_PORT"]),
        "protocol": "vless",
        "settings": {"clients": [], "decryption": "none"},
        "sniffing": {"enabled": True, "destOverride": ["http", "tls", "quic"]},
        "streamSettings": {
            "network": "xhttp",
            "security": "reality",
            "realitySettings": {
                "show": False, "xver": 0,
                "target": f"{os.environ['RW_REALITY_XHTTP_SNI']}:443",
