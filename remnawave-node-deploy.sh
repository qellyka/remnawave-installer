read_domain() {
  local prompt="$1" __resultvar="$2" value
  while true; do
    read -rp "$prompt" value
    value=$(printf '%s' "$value" | tr -cd 'a-zA-Z0-9.-')
    if [[ "$value" =~ ^[a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(\.[a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)+$ ]]; then
      printf -v "$__resultvar" '%s' "$value"
      return 0
    fi
    warn "Похоже на некорректный домен — возможно, при вводе/вставке приклеился"
    warn "случайный символ (например от переключения раскладки). Введи ещё раз."
  done
}

# Reads a panel URL and accepts either a bare domain (panel.example.com) or
# a full URL (https://panel.example.com) — normalizes to always have a
# scheme, since it's easy to type either form out of habit and Python's
# urllib rejects a bare hostname outright with a confusing traceback.
read_panel_url() {
  local prompt="$1" __resultvar="$2" value
  read -rp "$prompt" value
  if [[ ! "$value" =~ ^https?:// ]]; then
    value="https://$value"
  fi
  printf -v "$__resultvar" '%s' "$value"
}

