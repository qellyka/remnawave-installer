#!/usr/bin/env python3
"""
Remnawave config-profile lister — by qellyka
Fetches existing config profiles + their inbounds and prints them as
pipe-delimited lines for a bash picker:
  PROFILE|<num>|<uuid>|<name>
  INBOUND|<profile_num>|<inbound_num>|<uuid>|<tag>|<network>|<security>|<port>

CDN-type inbounds (network=xhttp, security=none) are excluded — reusing one
on a different node would still need its own domain/Host, so there is
nothing to actually save by picking it here, and the raw listing doesn't
expose the path this specific inbound type needs.
"""
import json
import os
import sys
import urllib.request
import urllib.error

PANEL_URL = os.environ.get("RW_PANEL_URL", "")
API_TOKEN = os.environ.get("RW_API_TOKEN", "")

if not all([PANEL_URL, API_TOKEN]):
    print("[ERROR] Missing RW_PANEL_URL / RW_API_TOKEN", file=sys.stderr)
    sys.exit(1)

req = urllib.request.Request(PANEL_URL.rstrip("/") + "/api/config-profiles", method="GET")
req.add_header("Authorization", f"Bearer {API_TOKEN}")
try:
    with urllib.request.urlopen(req, timeout=15) as resp:
        data = json.loads(resp.read().decode())
except (urllib.error.URLError, urllib.error.HTTPError) as e:
    print(f"[ERROR] Could not fetch config profiles: {e}", file=sys.stderr)
    sys.exit(1)

profiles = data.get("response", {}).get("configProfiles", [])
if not profiles:
    print("[ERROR] No config profiles found in this panel", file=sys.stderr)
    sys.exit(2)

any_inbound_shown = False
for pi, p in enumerate(profiles, start=1):
    print(f"PROFILE|{pi}|{p['uuid']}|{p.get('name', '?')}")
    ii = 0
    for ib in p.get("inbounds", []):
        if ib.get("network") == "xhttp" and ib.get("security") == "none":
            continue  # CDN-type — not reusable through this picker, see docstring
        ii += 1
        any_inbound_shown = True
        print(f"INBOUND|{pi}|{ii}|{ib['uuid']}|{ib.get('tag', '?')}|{ib.get('network', '?')}|{ib.get('security', '?')}|{ib.get('port', '?')}")

if not any_inbound_shown:
    print("[ERROR] No reusable (non-CDN) inbounds found in any profile", file=sys.stderr)
    sys.exit(3)
LISTEOF
}

