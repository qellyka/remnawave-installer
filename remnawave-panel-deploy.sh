install_base() {
  log "Обновляю систему..."
  export DEBIAN_FRONTEND=noninteractive
  apt update -qq
  apt upgrade -y -qq
  apt install -y -qq curl openssl jq nftables dnsutils

  if command -v ufw >/dev/null 2>&1 && LC_ALL=C ufw status 2>/dev/null | grep -q "Status: active"; then
    warn "UFW активен — отключаю в пользу nftables"
    ufw --force disable >/dev/null 2>&1 || true
  fi

  if ! command -v docker >/dev/null 2>&1; then
    log "Устанавливаю Docker..."
    curl -fsSL https://get.docker.com | sh
  fi
  docker compose version >/dev/null 2>&1 || die "Docker Compose plugin недоступен после установки"
}

write_nftables_base() {
  log "Записываю базовые правила nftables..."
  [[ -f /etc/nftables.conf ]] && cp /etc/nftables.conf "/etc/nftables.conf.bak.$(date +%s)"

  local icmp_rule="        icmp type echo-request accept"
  if [[ "${BLOCK_ICMP:-false}" == true ]]; then
    icmp_rule="        # ICMP echo-request blocked (--block-icmp)"
  fi

  cat > /etc/nftables.conf <<EOF
#!/usr/sbin/nft -f
# Generated by remnawave-deploy.sh — by qellyka
#
# IMPORTANT: only ever flush OUR OWN table (inet filter), never the whole
# ruleset. Docker keeps its own port-publishing (DNAT) rules in a separate
# table (ip nat) — a global "flush ruleset" wipes those out too and breaks
# every published container port on the host, including ones already
# running. "table inet filter {}" makes the flush below a no-op (rather
# than an error) the very first time this runs, before the table exists.
table inet filter {}
flush table inet filter

table inet filter {
    chain input {
        type filter hook input priority filter; policy drop;
        ct state invalid drop
        ct state established,related accept
        iif lo accept
        tcp dport $SSH_PORT accept
$icmp_rule
${EXTRA_INPUT_RULES:-}
    }
    chain forward {
        type filter hook forward priority filter; policy drop;
    }
    chain output {
        type filter hook output priority filter; policy accept;
    }
}
EOF
  nft -c -f /etc/nftables.conf || die "Синтаксическая ошибка nftables — проверь /etc/nftables.conf"
  nft -f /etc/nftables.conf
  systemctl enable nftables >/dev/null 2>&1 || true
  systemctl restart nftables
}

generate_reality_keys() {
  # Populates REALITY_PRIVATE_KEY / REALITY_PUBLIC_KEY / REALITY_SHORTID
  if ! command -v xray >/dev/null 2>&1; then
    log "Устанавливаю Xray-core (только для генерации ключей Reality)..."
    bash -c "$(curl -Ls https://raw.githubusercontent.com/XTLS/Xray-install/main/install-release.sh)" @ install >/dev/null 2>&1
  fi
  local keys
  keys=$(xray x25519)
  REALITY_PRIVATE_KEY=$(echo "$keys" | grep -i "Private" | awk '{print $NF}')
  REALITY_PUBLIC_KEY=$(echo "$keys" | grep -i "Public" | awk '{print $NF}')
  REALITY_SHORTID=$(openssl rand -hex 8)
  [[ -n "$REALITY_PRIVATE_KEY" && -n "$REALITY_PUBLIC_KEY" ]] || die "Не удалось сгенерировать ключи Reality"
}

generate_hy2_cert() {
  mkdir -p /etc/xray-certs
  if [[ ! -f /etc/xray-certs/hy2-cert.crt ]]; then
    openssl req -x509 -nodes -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 \
      -keyout /etc/xray-certs/hy2-key.pem \
      -out /etc/xray-certs/hy2-cert.crt \
      -days 3650 -subj "/CN=www.bing.com" >/dev/null 2>&1
  fi
}

write_nginx_hardening() {
  # Shared SSL/gzip snippet — one place, included by every server block that needs it.
  mkdir -p /etc/nginx/snippets
  cat > /etc/nginx/snippets/ssl-params.conf <<'EOF'
ssl_protocols          TLSv1.2 TLSv1.3;
ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305:DHE-RSA-AES128-GCM-SHA256:DHE-RSA-AES256-GCM-SHA384:DHE-RSA-CHACHA20-POLY1305;
ssl_session_timeout 1d;
ssl_session_cache shared:MozSSL:10m;
ssl_session_tickets off;
ssl_stapling on;
ssl_stapling_verify on;
resolver 1.1.1.1 1.0.0.1 8.8.8.8 8.8.4.4 valid=60s;
resolver_timeout 2s;

gzip on;
gzip_vary on;
gzip_proxied any;
gzip_comp_level 6;
gzip_buffers 16 8k;
gzip_http_version 1.1;
gzip_min_length 256;
gzip_types
    application/atom+xml application/geo+json application/javascript
    application/x-javascript application/json application/ld+json
    application/manifest+json application/rdf+xml application/rss+xml
    application/xhtml+xml application/xml application/wasm
    font/eot font/otf font/ttf image/svg+xml
    text/css text/javascript text/plain text/xml;
EOF

  # Any TLS connection with an SNI that doesn't match a configured server_name
  # gets the handshake dropped outright, instead of falling through to some
  # default vhost or error page — gives a port-scanner nothing to work with.
  cat > /etc/nginx/sites-available/00-reject-unknown-sni <<'EOF'
server {
    listen 443 ssl default_server;
    listen [::]:443 ssl default_server;
    server_name _;
    ssl_reject_handshake on;
}
EOF
  ln -sf /etc/nginx/sites-available/00-reject-unknown-sni /etc/nginx/sites-enabled/
}

issue_cert_for_domain() {
  local domain="$1"
  log "Проверяю DNS для $domain..."
  local resolved public_ip
  resolved=$(dig +short "$domain" A | tail -n1 || true)
  public_ip=$(curl -s -4 --max-time 5 https://api.ipify.org || true)
  if [[ -z "$resolved" ]]; then
    warn "$domain пока не резолвится. Certbot, скорее всего, не пройдёт, пока не создашь A-запись -> $public_ip"
  elif [[ "$resolved" != "$public_ip" ]]; then
    warn "$domain резолвится в $resolved, а не в IP этого сервера ($public_ip). Certbot может не пройти."
  fi

  if [[ ! -d "/etc/letsencrypt/live/$domain" ]]; then
    mkdir -p /var/www/certbot
    cat > "/etc/nginx/sites-available/$domain.bootstrap" <<EOF
server {
    listen 80;
    server_name $domain;
    location /.well-known/acme-challenge/ { root /var/www/certbot; }
    location / { return 404; }
}
EOF
    ln -sf "/etc/nginx/sites-available/$domain.bootstrap" "/etc/nginx/sites-enabled/$domain.bootstrap"
    nginx -t && systemctl reload nginx

    certbot certonly --webroot -w /var/www/certbot -d "$domain" --non-interactive --agree-tos \
      -m "admin@$domain" --no-eff-email || warn "Certbot не смог получить сертификат для $domain — поправь DNS и запусти certbot вручную позже"

    rm -f "/etc/nginx/sites-enabled/$domain.bootstrap" "/etc/nginx/sites-available/$domain.bootstrap"
  else
    log "Сертификат для $domain уже есть — пропускаю выпуск."
  fi
}

