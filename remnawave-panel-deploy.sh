  cd /opt/remnawave

  if [[ -f .env && -f docker-compose.yml ]]; then
    log ".env уже существует — повторный запуск, секреты не трогаю (иначе пароль Postgres"
    log "разойдётся с уже инициализированной базой, и панель уйдёт в цикл рестартов)."
    PG_PW=$(grep "^POSTGRES_PASSWORD=" .env | cut -d= -f2-)
    grep -q "^FRONT_END_DOMAIN=" .env && sed -i "s/^FRONT_END_DOMAIN=.*/FRONT_END_DOMAIN=$PANEL_DOMAIN/" .env
    grep -q "^SUB_PUBLIC_DOMAIN=" .env && sed -i "s/^SUB_PUBLIC_DOMAIN=.*/SUB_PUBLIC_DOMAIN=$SUB_DOMAIN/" .env
  else
    log "Скачиваю официальные шаблоны docker-compose и .env..."
    curl -fsSL -o docker-compose.yml https://raw.githubusercontent.com/remnawave/backend/refs/heads/main/docker-compose-prod.yml
    curl -fsSL -o .env https://raw.githubusercontent.com/remnawave/backend/refs/heads/main/.env.sample

    log "Генерирую секреты..."
    sed -i "s/^APP_SECRET=.*/APP_SECRET=$(openssl rand -hex 64)/" .env
    sed -i "s/^JWT_AUTH_SECRET=.*/JWT_AUTH_SECRET=$(openssl rand -hex 64)/" .env
    sed -i "s/^JWT_API_TOKENS_SECRET=.*/JWT_API_TOKENS_SECRET=$(openssl rand -hex 64)/" .env
    sed -i "s/^METRICS_PASS=.*/METRICS_PASS=$(openssl rand -hex 64)/" .env
    sed -i "s/^WEBHOOK_SECRET_HEADER=.*/WEBHOOK_SECRET_HEADER=$(openssl rand -hex 64)/" .env
    PG_PW=$(openssl rand -hex 24)
    sed -i "s/^POSTGRES_PASSWORD=.*/POSTGRES_PASSWORD=$PG_PW/" .env
    sed -i "s|^\(DATABASE_URL=\"postgresql://postgres:\)[^@]*\(@.*\)|\1$PG_PW\2|" .env
    grep -q "^FRONT_END_DOMAIN=" .env && sed -i "s/^FRONT_END_DOMAIN=.*/FRONT_END_DOMAIN=$PANEL_DOMAIN/" .env
    grep -q "^SUB_PUBLIC_DOMAIN=" .env && sed -i "s/^SUB_PUBLIC_DOMAIN=.*/SUB_PUBLIC_DOMAIN=$SUB_DOMAIN/" .env
  fi

  log "Запускаю контейнеры панели..."
  docker compose up -d

  issue_cert_for_domain "$PANEL_DOMAIN"
  issue_cert_for_domain "$SUB_DOMAIN"

  write_nginx_hardening

  log "Пишу конфиги Nginx..."
  if [[ -d "/etc/letsencrypt/live/$PANEL_DOMAIN" ]]; then
    cat > /etc/nginx/sites-available/remnawave-panel <<EOF
server {
    listen 80; server_name $PANEL_DOMAIN;
    return 301 https://\$host\$request_uri;
}
server {
    listen 443 ssl; http2 on; server_name $PANEL_DOMAIN;
    ssl_certificate     /etc/letsencrypt/live/$PANEL_DOMAIN/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$PANEL_DOMAIN/privkey.pem;
    include /etc/nginx/snippets/ssl-params.conf;
    location / {
        proxy_pass http://127.0.0.1:3000;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
    }
}
EOF
  else
    warn "Сертификата для $PANEL_DOMAIN нет — пишу временный HTTP-конфиг без HTTPS."
    cat > /etc/nginx/sites-available/remnawave-panel <<EOF
server {
    listen 80; server_name $PANEL_DOMAIN;
    location /.well-known/acme-challenge/ { root /var/www/certbot; }
    location / { return 503 'Сертификат ещё не выпущен — перезапусти certbot вручную.'; }
}
EOF
  fi

  if [[ -d "/etc/letsencrypt/live/$SUB_DOMAIN" ]]; then
    cat > /etc/nginx/sites-available/remnawave-sub <<EOF
server {
    listen 80; server_name $SUB_DOMAIN;
    return 301 https://\$host\$request_uri;
}
server {
    listen 443 ssl; http2 on; server_name $SUB_DOMAIN;
    ssl_certificate     /etc/letsencrypt/live/$SUB_DOMAIN/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$SUB_DOMAIN/privkey.pem;
    include /etc/nginx/snippets/ssl-params.conf;
    location / {
        proxy_pass http://127.0.0.1:3010;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Host \$host;
        proxy_set_header X-Forwarded-Port \$server_port;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
    }
}
EOF
  else
    warn "Сертификата для $SUB_DOMAIN нет — пишу временный HTTP-конфиг без HTTPS."
    cat > /etc/nginx/sites-available/remnawave-sub <<EOF
server {
    listen 80; server_name $SUB_DOMAIN;
    location /.well-known/acme-challenge/ { root /var/www/certbot; }
    location / { return 503 'Сертификат ещё не выпущен — перезапусти certbot вручную.'; }
}
EOF
  fi
  ln -sf /etc/nginx/sites-available/remnawave-panel /etc/nginx/sites-enabled/
  ln -sf /etc/nginx/sites-available/remnawave-sub /etc/nginx/sites-enabled/
  rm -f /etc/nginx/sites-enabled/default
  nginx -t && systemctl reload nginx
  if [[ ! -d "/etc/letsencrypt/live/$PANEL_DOMAIN" || ! -d "/etc/letsencrypt/live/$SUB_DOMAIN" ]]; then
    warn "Один или оба домена работают пока без HTTPS (см. предупреждения выше)."
    warn "Когда лимит Let's Encrypt снимется (сообщение certbot указывает точное время),"
    warn "запусти: certbot certonly --webroot -w /var/www/certbot -d ДОМЕН, затем"
    warn "перезапусти установку панели ещё раз — она сама допишет нормальный HTTPS-конфиг."
  fi

  EXTRA_INPUT_RULES="        tcp dport { 80, 443 } accept"
  write_nftables_base

  echo ""
  echo "Создать первого администратора автоматически, прямо сейчас?"
  echo "  1) Да (работает только для только что установленной, ещё пустой панели)"
  echo "  2) Нет — сделаю сам в UI позже (страницу подписки придётся донастроить вручную)"
  read -rp "Введите номер [1-2]: " BOOTSTRAP_CHOICE
  BOOTSTRAP_OK=false
  ADMIN_CREATED=false
  if [[ "$BOOTSTRAP_CHOICE" == "1" ]]; then
    read -rp "Логин администратора: " RW_ADMIN_USERNAME
    RW_ADMIN_PASSWORD=$(openssl rand -base64 18)
    apt install -y -qq python3
    write_bootstrap_script
    BOOTSTRAP_OUT=$(RW_PANEL_URL="https://$PANEL_DOMAIN" RW_ADMIN_USERNAME="$RW_ADMIN_USERNAME" RW_ADMIN_PASSWORD="$RW_ADMIN_PASSWORD" \
      python3 /opt/remnawave/remnawave_bootstrap.py 2>&1)
    echo "$BOOTSTRAP_OUT" | grep -q "^ADMIN_USERNAME=" && ADMIN_CREATED=true

    if [[ "$ADMIN_CREATED" == true ]]; then
      echo "ADMIN_USERNAME=$RW_ADMIN_USERNAME" > /opt/remnawave/bootstrap-credentials.txt
      echo "ADMIN_PASSWORD=$RW_ADMIN_PASSWORD" >> /opt/remnawave/bootstrap-credentials.txt
      chmod 600 /opt/remnawave/bootstrap-credentials.txt

      echo ""
      log "Администратор создан:"
      echo "  Логин:  $RW_ADMIN_USERNAME"
      echo "  Пароль: $RW_ADMIN_PASSWORD"
      echo "(сохранено в /opt/remnawave/bootstrap-credentials.txt, chmod 600)"
      echo ""
      echo "Создание токена через API у нас пока не работает надёжно (стабильно"
      echo "получаем 403 сразу после регистрации, хотя через UI создаётся без проблем)."
      echo "Зайди в панель — https://$PANEL_DOMAIN — под этими данными,"
      echo "создай токен: Settings -> API Tokens -> Create (шаблон под страницу"
      echo "подписки подходит — не обязательно давать полные права)."
      echo "Вставь готовый токен сюда."
      echo "(Enter без значения — пропустить, донастроишь подписку вручную позже)"
      read -rp "API-токен: " API_TOKEN_VALUE
      if [[ -n "$API_TOKEN_VALUE" ]]; then
        HTTP_CODE=$(curl -fsS -o /dev/null -w "%{http_code}" \
          -H "Authorization: Bearer $API_TOKEN_VALUE" "https://$PANEL_DOMAIN/api/hosts" || true)
        # 200 = полный доступ, 403 = токен настоящий и принят сервером, просто
        # без прав именно на управление хостами (например, создан по шаблону
        # конкретно под страницу подписки, с урезанными правами — это нормально
        # и ожидаемо, не признак битого токена). Только 401 значит, что сервер
        # вообще не признал токен — вот это уже похоже на опечатку при вставке.
        if [[ "$HTTP_CODE" == "200" || "$HTTP_CODE" == "403" ]]; then
          BOOTSTRAP_OK=true
          log "Токен принят сервером."
        elif [[ "$HTTP_CODE" == "401" ]]; then
          warn "Токен не прошёл проверку (401 — не распознан) — возможно, опечатка при вставке."
          warn "Страница подписки не получит REMNAWAVE_API_TOKEN автоматически."
        else
          warn "Не удалось проверить токен (код ответа: $HTTP_CODE) — сохраняю как есть,"
          warn "но сверь вручную, если страница подписки не заработает."
          BOOTSTRAP_OK=true
        fi
      fi
    else
      warn "Автосоздание администратора не удалось (см. вывод ниже) — создай его вручную через UI."
      echo "$BOOTSTRAP_OUT"
    fi
  fi

  echo ""
  echo "Создать Config Profile с 4 базовыми инбаундами прямо сейчас?"
  echo "Это чтобы при установке первой ноды было что сразу переиспользовать,"
  echo "а не создавать инбаунды с нуля отдельно для каждой ноды."
  echo "  1) Да (нужен API-токен — тот же, что и для страницы подписки)"
  echo "  2) Нет — создам позже, при установке ноды"
  read -rp "Введите номер [1-2]: " SEED_CHOICE
  if [[ "$SEED_CHOICE" == "1" ]]; then
    SEED_TOKEN="${API_TOKEN_VALUE:-}"
    if [[ -z "$SEED_TOKEN" ]]; then
      echo "Автобутстрап не дал токен — вставь его сам (Settings -> API Tokens в панели):"
      read -rp "API-токен: " SEED_TOKEN
    fi
    if [[ -n "$SEED_TOKEN" ]]; then
      seed_base_profile "https://$PANEL_DOMAIN" "$SEED_TOKEN"
    else
      warn "Токен не введён — профиль не создан."
    fi
  fi

  log "Разворачиваю сервер подписки..."
  mkdir -p /opt/remnawave/subscription
  cat > /opt/remnawave/subscription/docker-compose.yml <<'EOF'
services:
  remnawave-subscription-page:
    image: remnawave/subscription-page:latest
    container_name: remnawave-subscription-page
    hostname: remnawave-subscription-page
    restart: always
    env_file:
      - .env
    ports:
      - '127.0.0.1:3010:3010'
    networks:
      - remnawave-network
networks:
  remnawave-network:
    external: true
EOF
  cat > /opt/remnawave/subscription/.env <<EOF
APP_PORT=3010
REMNAWAVE_PANEL_URL=http://remnawave:3000
REMNAWAVE_API_TOKEN=${API_TOKEN_VALUE:-}
CUSTOM_SUB_PREFIX=
MARZBAN_LEGACY_LINK_ENABLED=false
MARZBAN_LEGACY_SECRET_KEY=
TRUST_PROXY=1
EOF
  if [[ "$BOOTSTRAP_OK" != true ]]; then
    warn "REMNAWAVE_API_TOKEN оставлен пустым в /opt/remnawave/subscription/.env"
    warn "Создай токен вручную (Settings -> API Tokens), впиши его туда, затем:"
    warn "  cd /opt/remnawave/subscription && docker compose up -d"
  fi
  cd /opt/remnawave/subscription
  docker compose up -d
  cd /opt/remnawave


  echo ""
  echo "==================================================="
  log "Панель установлена."
  echo "==================================================="
  echo "Панель:        https://$PANEL_DOMAIN"
  echo "Подписка:      https://$SUB_DOMAIN"
  echo "Пароль Postgres (также в /opt/remnawave/.env): $PG_PW"
  if [[ "$BOOTSTRAP_OK" == true ]]; then
    echo ""
    echo "Администратор создан, токен подтверждён и передан странице подписки:"
    echo "  Логин:  $RW_ADMIN_USERNAME"
    echo "  Пароль: $RW_ADMIN_PASSWORD"
    echo "  API-токен: $API_TOKEN_VALUE"
    echo "(сохранено в /opt/remnawave/bootstrap-credentials.txt, chmod 600)"
    echo ""
    echo "Можешь сразу запускать этот же скрипт в режиме ноды и вставить"
    echo "этот URL панели + этот API-токен при автопровижининге."
  elif [[ "$ADMIN_CREATED" == true ]]; then
    echo ""
    warn "Администратор создан, но токен не был передан (пропущен или не прошёл проверку)."
    echo "  Логин:  $RW_ADMIN_USERNAME"
    echo "  Пароль: $RW_ADMIN_PASSWORD"
    echo "(сохранено в /opt/remnawave/bootstrap-credentials.txt, chmod 600)"
    echo "Создай токен в панели (Settings -> API Tokens -> Create), впиши в"
    echo "/opt/remnawave/subscription/.env и перезапусти: docker compose up -d"
  else
    echo ""
    echo "Дальше: зайди в панель, создай админа, потом"
    echo "Settings -> API Tokens, чтобы получить токен для режима ноды."
  fi
  echo "==================================================="
}

if [[ "$TOP_MODE" == "seed_only" ]]; then
  read_domain "URL панели без https:// (например panel.example.com): " SEED_PANEL_HOST
  read -rp "API-токен: " SEED_ONLY_TOKEN
  [[ -n "$SEED_ONLY_TOKEN" ]] || die "Токен обязателен"
  apt-get update -qq >/dev/null 2>&1 || true
  apt-get install -y -qq curl openssl jq nftables python3 >/dev/null 2>&1
  mkdir -p /opt/remnawave
  seed_base_profile "https://$SEED_PANEL_HOST" "$SEED_ONLY_TOKEN"
